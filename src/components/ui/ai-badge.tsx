import { Bot, FlaskConical, PenLine } from "lucide-react";
import { Badge } from "./badge";
import { Tooltip } from "./tooltip";

/** Always-visible provenance label for generated content. */
export function OriginBadge({ origin }: { origin: "ai" | "simulated" | "manual" | string }) {
  if (origin === "simulated") {
    return (
      <Tooltip content="Generated by EduQuest's rule-based simulator from the source text. No AI model was used.">
        <Badge tone="ember" icon={<FlaskConical />}>
          Simulated
        </Badge>
      </Tooltip>
    );
  }
  if (origin === "ai") {
    return (
      <Tooltip content="Generated by an AI model from the source material. Review before relying on it.">
        <Badge tone="iris" icon={<Bot />}>
          AI-generated
        </Badge>
      </Tooltip>
    );
  }
  return (
    <Badge tone="neutral" icon={<PenLine />}>
      Teacher-made
    </Badge>
  );
}
